import fs from 'node:fs';
import path from 'node:path';
import Database from 'better-sqlite3';

const appRoot = path.resolve(import.meta.dirname, '..');
const dbPath = path.join(appRoot, 'legacy', 'dental.sqlite');
const outputPath = path.join(appRoot, 'src', 'domain', 'legacy-resources.generated.ts');

// M-07 降级路径：legacy/dental.sqlite 已从仓库移除（见 .env.example R2-P0-04）。
// 干净克隆/CI 上缺失该输入时，保留已提交的生成物并打印警告，而不是让
// better-sqlite3 抛出难读的打开失败。需要重新生成时先恢复 dental.sqlite。
if (!fs.existsSync(dbPath)) {
  console.warn(
    `[generate-legacy-resources] legacy/dental.sqlite not found (removed from repo, see .env.example R2-P0-04).\n` +
    `  Keeping committed ${path.relative(appRoot, outputPath)} unchanged. ` +
    'Restore legacy/dental.sqlite to regenerate legacy resource definitions.',
  );
  process.exit(0);
}
const db = new Database(dbPath, { readonly: true });

const BASE_COLUMNS = new Set(['id', 'clinicId', 'createdAt', 'updatedAt', 'deletedAt']);
const INTERNAL_TABLES = new Set([
  'BackupRecord',
  'IdempotencyRecord',
  'SyncChange',
  'SyncDevice',
  'UsedRefreshToken',
  'UserClinic',
]);
const resourcesSource = fs.readFileSync(path.join(appRoot, 'src', 'domain', 'resources.ts'), 'utf8');
const explicitTables = new Set(
  [...resourcesSource.matchAll(/crud\('([^']+)',\s*'([^']+)'/g)].map((match) => match[2]),
);
const NAME_OVERRIDES = {
  DataImportJob: 'dataImportJobs',
  InventoryReplenishmentSuggestion: 'inventoryReplenishmentSuggestions',
  PrintTemplate: 'printTemplates',
};

function fieldType(sqlType) {
  const type = String(sqlType ?? 'TEXT').toUpperCase();
  if (type.includes('INT') || type.includes('REAL') || type.includes('NUM') || type.includes('DEC')) return 'number';
  if (type.includes('BLOB')) return 'text';
  return 'text';
}

function lowerFirst(value) {
  return value.charAt(0).toLowerCase() + value.slice(1);
}

function resourceName(table) {
  return NAME_OVERRIDES[table] ?? lowerFirst(table);
}

function fieldLiteral(field) {
  const options = field.type === 'number' ? '' : '';
  return `{ name: ${JSON.stringify(field.name)}, type: '${field.type}'${options} }`;
}

const tables = db.prepare(
  "SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' AND name != 'schema_migrations' ORDER BY name",
).all();

const definitions = [];
for (const row of tables) {
  const table = row.name;
  if (explicitTables.has(table) || INTERNAL_TABLES.has(table)) continue;
  const columns = db.prepare(`PRAGMA table_info(${JSON.stringify(table)})`).all();
  const fields = columns
    .filter((column) => !BASE_COLUMNS.has(column.name))
    .map((column) => ({
      name: column.name,
      type: fieldType(column.type),
    }));
  const searchableFields = fields.filter((field) => field.type === 'text').slice(0, 3).map((field) => field.name);
  const hasCreatedAt = columns.some((column) => column.name === 'createdAt');
  const softDelete = columns.some((column) => column.name === 'deletedAt');
  const definition = [
    `  legacy(${JSON.stringify(resourceName(table))}, ${JSON.stringify(table)}, [`,
    ...fields.map((field) => `    ${fieldLiteral(field)},`),
    '  ], {',
    `    searchableFields: ${JSON.stringify(searchableFields)},`,
    `    defaultSort: { field: ${JSON.stringify(hasCreatedAt ? 'createdAt' : 'id')}, order: 'DESC' },`,
    `    capabilities: { list: true, create: false, update: false, delete: false, softDelete: ${softDelete} },`,
    "    roles: ['BOSS'],",
    '  })',
  ];
  definitions.push(definition.join('\n'));
}

const content = `// Generated by scripts/generate-legacy-resources.mjs. Do not edit by hand.
import type { ResourceDefinition, ResourceField, UserRole } from './contracts';

function legacy(
  name: string,
  table: string,
  fields: ResourceField[],
  options: {
    searchableFields?: string[];
    defaultSort?: { field: string; order: 'ASC' | 'DESC' };
    capabilities: ResourceDefinition['capabilities'];
    roles: UserRole[];
  },
): ResourceDefinition {
  return { name, table, fields, audit: false, ...options };
}

export const legacyResources: ResourceDefinition[] = [
${definitions.join(',\n')}
];
`;

fs.writeFileSync(outputPath, content, 'utf8');
db.close();
console.log(`generated ${definitions.length} legacy resource definitions -> ${path.relative(appRoot, outputPath)}`);
